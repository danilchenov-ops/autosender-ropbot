VOWEL_END = ('а', 'я')


def _forms(name: str):
    """Падежные формы имени в том виде, в каком они звучат в разговоре."""
    n = name
    out = {n}
    if n.endswith('ий'):                       # Дмитрий, Анатолий, Юрий
        st = n[:-2]
        out |= {st + s for s in ('ия', 'ию', 'ием', 'ии', 'ий')}
    elif n.endswith('й'):                      # Андрей, Николай, Сергей
        st = n[:-1]
        out |= {st + s for s in ('я', 'ю', 'ем', 'е')}
    elif n.endswith('ь'):                      # Игорь
        st = n[:-1]
        out |= {st + s for s in ('я', 'ю', 'ем', 'е')}
    elif n.endswith(VOWEL_END):                # Светлана, Илья, Ксюша, Толя
        st = n[:-1]
        soft = n.endswith('я')
        out |= {st + s for s in (('и', 'е', 'ю', 'ей') if soft
                                 else ('ы', 'е', 'у', 'ой'))}
    elif n.endswith('о'):                      # Марго — не склоняется
        pass
    else:                                      # Михаил, Борис, Артур
        st = n
        out |= {st + s for s in ('а', 'у', 'ом', 'е')}
    return out


NAME_FORMS = set()
for _n in BASE_NAMES.split():
    NAME_FORMS |= _forms(_n)

WORD = re.compile(r'[А-Яа-яЁё]{3,}')


def build_extra(manager_names):
    """Имена и фамилии менеджеров из CRM — со всеми падежными формами."""
    extra = set()
    for full in manager_names or []:
        for part in re.split(r'[\s.]+', full or ''):
            p = part.strip().lower().replace('ё', 'е')
            if len(p) >= 4 and re.fullmatch(r'[а-я]+', p):
                extra |= _forms(p)
    return extra


def scrub(text: str, extra_names=None) -> str:
    if not text:
        return text
    extra = extra_names or set()
    t = EMAIL.sub('[ПОЧТА]', text)
    t = URL.sub('[ССЫЛКА]', t)
    t = PHONE.sub('[ТЕЛЕФОН]', t)
    t = PHONE_RUN.sub('[ТЕЛЕФОН]', t)
    t = COMPANY.sub('[КОМПАНИЯ]', t)
    t = PATRONYM.sub('[ОТЧЕСТВО]', t)

    def repl(m):
        w = m.group(0)
        lw = w.lower().replace('ё', 'е')
        if lw in NAME_FORMS or lw in extra:
            return '[ИМЯ]'
        return w

    return WORD.sub(repl, t)
